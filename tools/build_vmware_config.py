#!/usr/bin/env python3
"""Generate the VMware profile validated for BlesKernOS's legacy SVGA3D driver."""
import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('disk', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    disk = args.disk.resolve()
    output = args.output.resolve()
    if not disk.is_file():
        parser.error(f'disk not found: {disk}')
    if disk.parent != output.parent:
        parser.error('keep the generated VMX beside its VMDK')
    # VMware string escaping is deliberately restricted to a filename here.
    if any(c in disk.name for c in '"\n\r\\'):
        parser.error('unsupported characters in disk filename')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(f'''# Generated by tools/build_vmware_config.py; see docs/graphics/SVGA3D_VALIDATION.md.
.encoding = "UTF-8"
config.version = "8"
virtualHW.version = "10"
displayName = "BlesKernOS 0.9 - SVGA3D legacy"
guestOS = "other"
firmware = "bios"
numvcpus = "1"
memsize = "256"
ide0:0.present = "TRUE"
ide0:0.fileName = "{disk.name}"
ide0:0.deviceType = "disk"
ide1:0.present = "FALSE"
floppy0.present = "FALSE"
mks.enable3d = "TRUE"
svga.vgpu10 = "FALSE"
svga.vramSize = "268435456"
svga.numDisplays = "1"
usb.present = "TRUE"
usb_xhci.present = "FALSE"
sound.present = "FALSE"
ethernet0.present = "FALSE"
serial0.present = "TRUE"
serial0.fileType = "file"
serial0.fileName = "bleskernos-serial.log"
serial0.fileAppend = "TRUE"
serial0.yieldOnMsrRead = "TRUE"
logging = "TRUE"
tools.syncTime = "FALSE"
''', encoding='utf-8')
    print(f'VMware legacy profile: {output}')


if __name__ == '__main__':
    main()
