#!/usr/bin/env python3
"""Generate exact historical GPU identities; no register/mode programming table.

Input is the licensed, pinned PCI ID database in third_party/pciids. A match is
only eligible for VBE fallback after live display class and BAR validation.
"""
import collections, hashlib, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/pciids/pci.ids'
FAMILY_NAMES = {0x1013: 'Cirrus GD54xx VBE', 0x5333: 'S3 Trio/ViRGE/Savage VBE',
                0x102b: 'Matrox Millennium/G-series VBE', 0x121a: '3dfx Banshee/Voodoo VBE',
                0x1039: 'SiS legacy VBE', 0x1023: 'Trident TGUI/Cyber/Blade VBE'}
def select(vendor, device, name):
    if vendor == 0x10de and re.match(r'^(NV[0-9A-F]{2}|G[89][0-9]B?|GT2[0-9]{2}|C51|C61|C67|MCP[678][0-9]).*\[(GeForce|Quadro|RIVA|Vanta|TNT)', name) and not re.search(r'Audio|Bridge|RAM|SMBus|Controller|ISA', name):
        return 'nvidia', 'NVIDIA RIVA/GeForce/Quadro VBE'
    if vendor == 0x1002 and re.match(r'^(R[1-6][0-9]{2}|RV[1-7][0-9]{2}|RS[1-8][0-9]{2}|Rage|3D Rage|Mach64|M[0-9]+)', name) and not re.search(r'Audio|Bridge|USB|SATA', name):
        return 'ati', 'ATI Rage/Radeon VBE'
    if vendor in FAMILY_NAMES and re.search(r'GD\s*54|Trio|ViRGE|Savage|Millennium|Mystique|G[1245][025][05]|Banshee|Voodoo [345]|Voodoo[345]|SiS.*VGA|[36][03][05].*VGA|TGUI|Cyber|Blade', name):
        return 'legacy', FAMILY_NAMES[vendor]
    return None

def generate():
    vendor = None
    devices = []
    for line in SOURCE.read_text().splitlines():
        if re.match(r'^[0-9a-f]{4} ', line):
            vendor = int(line[:4], 16)
        elif re.match(r'^\t[0-9a-f]{4} ', line):
            device, name = int(line[1:5], 16), line[7:].strip()
            family = select(vendor, device, name)
            if family:
                devices.append(dict(vendor=f'{vendor:04x}', device=f'{device:04x}',
                    group=family[0], family=family[1], model=name,
                    status='firmware_framebuffer_conditional'))
    assert len({(d['vendor'], d['device']) for d in devices}) == len(devices)
    for group in ('ati', 'nvidia', 'legacy'):
        text = ('/* SPDX-License-Identifier: BSD-3-Clause\n'
                ' * Generated by tools/generate_framebuffer_families.py from PCI ID Project data.\n'
                ' * Copyright Martin Mares and Albert Pool; third_party/pciids/COPYING.\n'
                ' * Identity only; use requires firmware mode and verified PCI aperture. */\n')
        for d in devices:
            if d['group'] == group:
                text += '    {0x%s, 0x%s, "%s"},\n' % (d['vendor'], d['device'], d['family'])
        (ROOT / f'kernel/drivers/graphics/families/{group}_vbe_ids.inc').write_text(text)
    manifest = dict(schema=1, source='https://github.com/pciutils/pciids/blob/master/pci.ids',
                    source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                    license='BSD-3-Clause', device_count=len(devices),
                    group_counts=dict(collections.Counter(d['group'] for d in devices)),
                    conditions=['PCI display class 03/00', 'VBE firmware linear framebuffer already initialized',
                                'supported dimensions/pitch/depth', 'framebuffer fully contained in live PCI memory BAR',
                                'CPU rendering only; existing native graphics drivers have priority'],
                    hardware_certified_count=0, devices=devices)
    (ROOT / 'docs/platform/framebuffer-device-catalog.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Generated:', manifest['device_count'], 'conditional framebuffer identities;', manifest['group_counts'])
if __name__ == '__main__':
    generate()
